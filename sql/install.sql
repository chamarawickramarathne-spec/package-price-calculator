-- =========================================================================
-- Package Price Calculator - ONE-SHOT DATABASE INSTALL (Supabase / Postgres)
--
-- HOW TO USE
--   1. Open the Supabase dashboard for this app's project.
--   2. SQL Editor -> New query.
--   3. Paste this ENTIRE file and press Run.  (One run - do not split it.)
--   4. Open the app's Equipment screen; the catalog and templates fill in.
--
-- WHAT IT DOES
--   1. Drops and recreates the application tables (exact mirror of the
--      original hiresmcq_lens_calculator schema).
--   2. Seeds categories, equipment types, the equipment catalog and templates.
--   3. Re-arms the id sequences so ids the app adds cannot collide.
--   4. Enables Row Level Security and grants the anon role exactly what the
--      app uses: SELECT + INSERT on the five catalog tables, and INSERT on
--      public.access_logs (append-only usage log).
--
-- SAFE TO RE-RUN: yes, as many times as you like. Re-running restores the
--   catalog to this snapshot. Saved packages are NOT affected - since v1.1.0
--   they are stored on the device (Room/SQLite), not in this database.
--   public.access_logs is NEVER dropped here, so usage history survives a
--   re-run.
--
-- SECURITY MODEL (interim)
--   The app authenticates with the project anon key, which is embedded in the
--   APK, so anyone holding the APK can read the catalog and add rows to it.
--   RLS makes that access explicit and documented; it does NOT make the catalog
--   private, and it does not allow anon to change or delete existing catalog
--   rows. HARDENING (recommended next step): enable Supabase Auth and replace
--   the anon policies with auth.uid()-based policies.
--
--   public.packages and public.package_equipment are deliberately NOT granted
--   to anon: saved packages are device-local, so the app never touches them
--   remotely. The REVOKE below also removes any grant left behind by the
--   earlier migrations/001_rls_policies.sql.
--
--   public.access_logs is append-only for anon: INSERT only, no SELECT, no
--   UPDATE, no DELETE. The app records app opens and PDF exports there so the
--   studio can measure usage. See migrations/002_usage_logs.sql and
--   usage_reports.sql.
-- =========================================================================

BEGIN;

-- ============================ drop (FK-safe) ============================
-- NOTE: public.access_logs is intentionally NOT in this list. Dropping it would
-- erase the usage history; it is created/upgraded in place further down.
DROP TABLE IF EXISTS public.package_equipment  CASCADE;
DROP TABLE IF EXISTS public.template_equipment CASCADE;
DROP TABLE IF EXISTS public.equipment_details  CASCADE;
DROP TABLE IF EXISTS public.packages           CASCADE;
DROP TABLE IF EXISTS public.templates          CASCADE;
DROP TABLE IF EXISTS public.equipment_types    CASCADE;
DROP TABLE IF EXISTS public.category_types     CASCADE;

-- ============================ structure ============================
CREATE TABLE public.category_types (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL UNIQUE,
    description   text,
    display_order integer DEFAULT 0,
    is_active     smallint DEFAULT 1,
    created_at    timestamptz DEFAULT now(),
    updated_at    timestamptz DEFAULT now()
);

CREATE TABLE public.equipment_types (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       varchar(100) NOT NULL UNIQUE,
    is_active  smallint DEFAULT 1,
    created_at timestamptz DEFAULT now()
);

CREATE TABLE public.equipment_details (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES public.category_types(id) ON DELETE CASCADE,
    type        integer NOT NULL REFERENCES public.equipment_types(id) ON DELETE CASCADE,
    model       varchar(150) NOT NULL,
    name        varchar(200) NOT NULL,
    value       numeric(10,2) NOT NULL DEFAULT 0.00,
    description text,
    is_active   smallint DEFAULT 1,
    created_at  timestamptz DEFAULT now(),
    updated_at  timestamptz DEFAULT now()
);
CREATE INDEX idx_equipment_category ON public.equipment_details(category_id);
CREATE INDEX idx_equipment_type     ON public.equipment_details(type);
CREATE INDEX idx_equipment_active   ON public.equipment_details(is_active);

CREATE TABLE public.templates (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(200) NOT NULL,
    description       text,
    labor_hours       numeric(5,2)  DEFAULT 0.00,
    hourly_rate       numeric(10,2) DEFAULT 0.00,
    margin_percentage numeric(5,2)  DEFAULT 0.00,
    is_active         smallint DEFAULT 1,
    created_at        timestamptz DEFAULT now(),
    updated_at        timestamptz DEFAULT now()
);

CREATE TABLE public.template_equipment (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id  integer NOT NULL REFERENCES public.templates(id) ON DELETE CASCADE,
    equipment_id integer NOT NULL REFERENCES public.equipment_details(id) ON DELETE CASCADE,
    quantity     integer DEFAULT 1,
    created_at   timestamptz DEFAULT now(),
    UNIQUE (template_id, equipment_id)
);
CREATE INDEX idx_template_equip_template  ON public.template_equipment(template_id);
CREATE INDEX idx_template_equip_equipment ON public.template_equipment(equipment_id);

CREATE TABLE public.packages (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_name      varchar(200) NOT NULL,
    client_name       varchar(200),
    template_id       integer REFERENCES public.templates(id) ON DELETE SET NULL,
    labor_hours       numeric(5,2)  DEFAULT 0.00,
    hourly_rate       numeric(10,2) DEFAULT 0.00,
    margin_percentage numeric(5,2)  DEFAULT 0.00,
    equipment_total   numeric(10,2) DEFAULT 0.00,
    labor_total       numeric(10,2) DEFAULT 0.00,
    subtotal          numeric(10,2) DEFAULT 0.00,
    margin_amount     numeric(10,2) DEFAULT 0.00,
    final_total       numeric(10,2) DEFAULT 0.00,
    notes             text,
    created_at        timestamptz DEFAULT now(),
    updated_at        timestamptz DEFAULT now()
);
CREATE INDEX idx_packages_client  ON public.packages(client_name);
CREATE INDEX idx_packages_created ON public.packages(created_at);

CREATE TABLE public.package_equipment (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id   integer NOT NULL REFERENCES public.packages(id) ON DELETE CASCADE,
    equipment_id integer NOT NULL REFERENCES public.equipment_details(id) ON DELETE CASCADE,
    quantity     integer DEFAULT 1,
    unit_value   numeric(10,2) NOT NULL,
    total_value  numeric(10,2) NOT NULL,
    created_at   timestamptz DEFAULT now()
);
CREATE INDEX idx_package_equip_package   ON public.package_equipment(package_id);
CREATE INDEX idx_package_equip_equipment ON public.package_equipment(equipment_id);

-- Usage log. NON-DESTRUCTIVE: created if missing, upgraded in place if it
-- already exists, and never dropped - so app open / PDF export history and the
-- legacy web rows both survive a re-run. See migrations/002_usage_logs.sql.
CREATE TABLE IF NOT EXISTS public.access_logs (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address  varchar(45),
    user_agent  text,
    request_uri varchar(255),
    accessed_at timestamptz DEFAULT now(),
    event_type  varchar(32),
    device_id   varchar(64),
    app_version varchar(20),
    platform    varchar(16)
);
ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS event_type  varchar(32);
ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS device_id   varchar(64);
ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS app_version varchar(20);
ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS platform    varchar(16);
ALTER TABLE public.access_logs ALTER COLUMN ip_address DROP NOT NULL;
CREATE INDEX IF NOT EXISTS idx_access_logs_ip       ON public.access_logs(ip_address);
CREATE INDEX IF NOT EXISTS idx_access_logs_accessed ON public.access_logs(accessed_at);
CREATE INDEX IF NOT EXISTS idx_access_logs_event    ON public.access_logs(event_type);
CREATE INDEX IF NOT EXISTS idx_access_logs_device   ON public.access_logs(device_id);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_access_logs_event_type') THEN
        ALTER TABLE public.access_logs
            ADD CONSTRAINT ck_access_logs_event_type
            CHECK (event_type IS NULL OR char_length(event_type) BETWEEN 3 AND 32);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_access_logs_device_id') THEN
        ALTER TABLE public.access_logs
            ADD CONSTRAINT ck_access_logs_device_id
            CHECK (device_id IS NULL OR char_length(device_id) BETWEEN 1 AND 64);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_access_logs_app_version') THEN
        ALTER TABLE public.access_logs
            ADD CONSTRAINT ck_access_logs_app_version
            CHECK (app_version IS NULL OR char_length(app_version) <= 20);
    END IF;
END $$;

-- ON UPDATE CURRENT_TIMESTAMP equivalent
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_category_types_updated    BEFORE UPDATE ON public.category_types    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER trg_equipment_details_updated BEFORE UPDATE ON public.equipment_details FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER trg_templates_updated         BEFORE UPDATE ON public.templates         FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER trg_packages_updated          BEFORE UPDATE ON public.packages          FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

