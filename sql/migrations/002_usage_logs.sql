-- =========================================================================
-- Package Price Calculator - Migration 002: app usage logging
--
-- Adds append-only usage logging to public.access_logs so the studio can see
-- how many people use the app and how often PDFs are exported.
--
-- IMPORTANT
--   * This migration is NON-DESTRUCTIVE: it never drops the table and never
--     deletes rows. Existing rows (the legacy web log) are preserved.
--   * Run AFTER sql/migrations/001_rls_policies.sql. File 001 revokes
--     access_logs from anon; this file grants back INSERT only.
--   * sql/install.sql already contains this exact block, so a fresh install
--     does not need to run this file separately.
--
-- WHY THE COLUMNS CHANGE
--   The original table came from a web server (ip_address NOT NULL, user_agent,
--   request_uri). A mobile app cannot know its own public IP address, so
--   ip_address becomes nullable and the app records what it does know:
--     event_type  - "app_open" or "pdf_export"
--     device_id   - salted-free SHA-256 of ANDROID_ID, truncated to 32 hex
--     app_version - e.g. "1.3.0"
--     platform    - "android"
--   request_uri keeps the web-log convention: "/app/open", "/pdf/share",
--   "/pdf/save".
--
-- SECURITY MODEL
--   anon may INSERT only. There is deliberately no SELECT / UPDATE / DELETE
--   policy, so the (public) anon key cannot read or alter the log. Length
--   CHECKs bound junk rows. Because the anon key ships in the APK, a
--   determined client could still spam inserts - accepted for now; move to
--   Supabase Auth (or an RPC) if that becomes a problem.
-- =========================================================================

BEGIN;

-- ============================ table (non-destructive) ============================
CREATE TABLE IF NOT EXISTS public.access_logs (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address  varchar(45),
    user_agent  text,
    request_uri varchar(255),
    accessed_at timestamptz DEFAULT now(),
    event_type  varchar(32),
    device_id   varchar(64),
    app_version varchar(20),
    platform    varchar(16)
);

ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS event_type  varchar(32);
ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS device_id   varchar(64);
ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS app_version varchar(20);
ALTER TABLE public.access_logs ADD COLUMN IF NOT EXISTS platform    varchar(16);
ALTER TABLE public.access_logs ALTER COLUMN ip_address DROP NOT NULL;

-- ============================ indexes ============================
CREATE INDEX IF NOT EXISTS idx_access_logs_ip       ON public.access_logs(ip_address);
CREATE INDEX IF NOT EXISTS idx_access_logs_accessed ON public.access_logs(accessed_at);
CREATE INDEX IF NOT EXISTS idx_access_logs_event    ON public.access_logs(event_type);
CREATE INDEX IF NOT EXISTS idx_access_logs_device   ON public.access_logs(device_id);

-- ============================ length guards ============================
-- Bound abuse without locking out future event names (no value allow-list).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_access_logs_event_type') THEN
        ALTER TABLE public.access_logs
            ADD CONSTRAINT ck_access_logs_event_type
            CHECK (event_type IS NULL OR char_length(event_type) BETWEEN 3 AND 32);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_access_logs_device_id') THEN
        ALTER TABLE public.access_logs
            ADD CONSTRAINT ck_access_logs_device_id
            CHECK (device_id IS NULL OR char_length(device_id) BETWEEN 1 AND 64);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_access_logs_app_version') THEN
        ALTER TABLE public.access_logs
            ADD CONSTRAINT ck_access_logs_app_version
            CHECK (app_version IS NULL OR char_length(app_version) <= 20);
    END IF;
END $$;

-- ============================ grants ============================
-- Remove any earlier grant, then allow appends only.
REVOKE ALL ON TABLE public.access_logs FROM anon;
GRANT INSERT ON TABLE public.access_logs TO anon;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO anon;

-- ============================ RLS ============================
ALTER TABLE public.access_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS anon_all_access_logs ON public.access_logs;
DROP POLICY IF EXISTS anon_ins_access_logs ON public.access_logs;

CREATE POLICY anon_ins_access_logs ON public.access_logs
    FOR INSERT TO anon WITH CHECK (true);

-- Deliberate: no SELECT / UPDATE / DELETE policy exists, so anon can only append.

-- ============================ verify ============================
-- Expect: inserts_ok = 1 row (the policy), and the new columns present.
SELECT column_name, data_type, is_nullable
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'access_logs'
ORDER BY ordinal_position;

SELECT policyname, cmd, roles
FROM pg_policies
WHERE schemaname = 'public' AND tablename = 'access_logs';

COMMIT;
