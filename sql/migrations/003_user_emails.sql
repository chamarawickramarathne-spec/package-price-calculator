-- =========================================================================
-- Package Price Calculator - Migration 003: user email sign-in
--
-- Adds public.user_emails: the list of email addresses users type on the
-- app's sign-in screen (v1.3.0+). The studio uses this list to promote its
-- other applications.
--
-- IMPORTANT
--   * NON-DESTRUCTIVE: the table is created if missing and never dropped or
--     purged, so collected emails survive every re-run. sql/install.sql
--     mirrors this exact block, so a fresh install does not need this file.
--   * Run AFTER sql/migrations/001_rls_policies.sql (depends on the anon
--     role existing with its base grants).
--
-- WHY NO PASSWORD / NO AUTH
--   The app uses a soft identity gate: the user enters an email once, the
--   device remembers it, and the row is recorded here. There is no session,
--   no verification and no Supabase Auth involved - this table is a lead
--   list, not an accounts table.
--
-- SECURITY MODEL
--   anon may INSERT only. There is deliberately no SELECT / UPDATE / DELETE
--   policy, so the (public) anon key cannot read back or alter the list;
--   emails are read from the Supabase dashboard / table editor instead.
--   email is UNIQUE and the app lowercases + trims before inserting, so
--   re-submits (retry after offline, same person on a new install) collapse
--   into one row: the app sends a plain INSERT and treats the resulting
--   HTTP 409 as "already recorded". It must NOT send PostgREST's
--   ?on_conflict / Prefer: resolution=* - any ON CONFLICT clause with an
--   arbiter requires SELECT on the relation (PostgreSQL INSERT docs), which
--   would force this lead list to be readable through the public anon key.
--   Length CHECKs bound junk rows. As with access_logs, a determined client
--   holding the APK could spam inserts - accepted for now; move to Supabase
--   Auth (or an RPC) if that becomes a problem.
-- =========================================================================

BEGIN;

-- ============================ table (non-destructive) ============================
CREATE TABLE IF NOT EXISTS public.user_emails (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       varchar(320) NOT NULL UNIQUE,
    device_id   varchar(64),
    app_version varchar(20),
    platform    varchar(16),
    created_at  timestamptz DEFAULT now()
);

-- ============================ indexes ============================
CREATE INDEX IF NOT EXISTS idx_user_emails_created ON public.user_emails(created_at);

-- ============================ length guards ============================
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_user_emails_email') THEN
        ALTER TABLE public.user_emails
            ADD CONSTRAINT ck_user_emails_email
            CHECK (char_length(email) BETWEEN 3 AND 320);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_user_emails_device_id') THEN
        ALTER TABLE public.user_emails
            ADD CONSTRAINT ck_user_emails_device_id
            CHECK (device_id IS NULL OR char_length(device_id) BETWEEN 1 AND 64);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_user_emails_app_version') THEN
        ALTER TABLE public.user_emails
            ADD CONSTRAINT ck_user_emails_app_version
            CHECK (app_version IS NULL OR char_length(app_version) <= 20);
    END IF;
END $$;

-- ============================ grants ============================
-- Remove any earlier grant, then allow appends only.
REVOKE ALL ON TABLE public.user_emails FROM anon;
GRANT INSERT ON TABLE public.user_emails TO anon;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO anon;

-- ============================ RLS ============================
ALTER TABLE public.user_emails ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS anon_all_user_emails ON public.user_emails;
DROP POLICY IF EXISTS anon_ins_user_emails ON public.user_emails;

CREATE POLICY anon_ins_user_emails ON public.user_emails
    FOR INSERT TO anon WITH CHECK (true);

-- Deliberate: no SELECT / UPDATE / DELETE policy exists, so anon can only append.

-- ============================ verify ============================
-- Expect: one INSERT row (the policy) and the five columns.
SELECT column_name, data_type, is_nullable
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'user_emails'
ORDER BY ordinal_position;

SELECT policyname, cmd, roles
FROM pg_policies
WHERE schemaname = 'public' AND tablename = 'user_emails';

COMMIT;
