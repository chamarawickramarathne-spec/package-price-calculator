-- ============================ category_types ============================
CREATE TABLE IF NOT EXISTS public.category_types (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL UNIQUE,
    description   text,
    display_order integer DEFAULT 0,
    is_active     smallint DEFAULT 1,
    created_at    timestamptz DEFAULT now(),
    updated_at    timestamptz DEFAULT now()
);

-- ============================ equipment_types ============================
CREATE TABLE IF NOT EXISTS public.equipment_types (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       varchar(100) NOT NULL UNIQUE,
    is_active  smallint DEFAULT 1,
    created_at timestamptz DEFAULT now()
);

-- ============================ equipment_details ============================
-- NOTE: The production column is literally named "type" (FK to equipment_types.id).
-- It is intentionally kept as-is to match the running application code.
CREATE TABLE IF NOT EXISTS public.equipment_details (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES public.category_types(id) ON DELETE CASCADE,
    type        integer NOT NULL REFERENCES public.equipment_types(id) ON DELETE CASCADE,
    model       varchar(150) NOT NULL,
    name        varchar(200) NOT NULL,
    value       numeric(10,2) NOT NULL DEFAULT 0.00,
    description text,
    is_active   smallint DEFAULT 1,
    created_at  timestamptz DEFAULT now(),
    updated_at  timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_equipment_category ON public.equipment_details(category_id);
CREATE INDEX IF NOT EXISTS idx_equipment_type    ON public.equipment_details(type);
CREATE INDEX IF NOT EXISTS idx_equipment_active  ON public.equipment_details(is_active);

-- ============================ templates ============================
CREATE TABLE IF NOT EXISTS public.templates (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(200) NOT NULL,
    description       text,
    labor_hours       numeric(5,2) DEFAULT 0.00,
    hourly_rate       numeric(10,2) DEFAULT 0.00,
    margin_percentage numeric(5,2) DEFAULT 0.00,
    is_active         smallint DEFAULT 1,
    created_at        timestamptz DEFAULT now(),
    updated_at        timestamptz DEFAULT now()
);

-- ============================ template_equipment ============================
CREATE TABLE IF NOT EXISTS public.template_equipment (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id  integer NOT NULL REFERENCES public.templates(id) ON DELETE CASCADE,
    equipment_id integer NOT NULL REFERENCES public.equipment_details(id) ON DELETE CASCADE,
    quantity     integer DEFAULT 1,
    created_at   timestamptz DEFAULT now(),
    UNIQUE (template_id, equipment_id)
);

CREATE INDEX IF NOT EXISTS idx_template_equip_template ON public.template_equipment(template_id);
CREATE INDEX IF NOT EXISTS idx_template_equip_equipment ON public.template_equipment(equipment_id);

-- ============================ packages ============================
CREATE TABLE IF NOT EXISTS public.packages (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_name      varchar(200) NOT NULL,
    client_name       varchar(200),
    template_id       integer REFERENCES public.templates(id) ON DELETE SET NULL,
    labor_hours       numeric(5,2) DEFAULT 0.00,
    hourly_rate       numeric(10,2) DEFAULT 0.00,
    margin_percentage numeric(5,2) DEFAULT 0.00,
    equipment_total   numeric(10,2) DEFAULT 0.00,
    labor_total       numeric(10,2) DEFAULT 0.00,
    subtotal          numeric(10,2) DEFAULT 0.00,
    margin_amount     numeric(10,2) DEFAULT 0.00,
    final_total       numeric(10,2) DEFAULT 0.00,
    notes             text,
    created_at        timestamptz DEFAULT now(),
    updated_at        timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_packages_client  ON public.packages(client_name);
CREATE INDEX IF NOT EXISTS idx_packages_created ON public.packages(created_at);

-- ============================ package_equipment ============================
CREATE TABLE IF NOT EXISTS public.package_equipment (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id   integer NOT NULL REFERENCES public.packages(id) ON DELETE CASCADE,
    equipment_id integer NOT NULL REFERENCES public.equipment_details(id) ON DELETE CASCADE,
    quantity     integer DEFAULT 1,
    unit_value   numeric(10,2) NOT NULL,
    total_value  numeric(10,2) NOT NULL,
    created_at   timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_package_equip_package ON public.package_equipment(package_id);
CREATE INDEX IF NOT EXISTS idx_package_equip_equipment ON public.package_equipment(equipment_id);

-- ============================ access_logs ============================
CREATE TABLE IF NOT EXISTS public.access_logs (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address  varchar(45) NOT NULL,
    user_agent  text,
    request_uri varchar(255),
    accessed_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_access_logs_ip       ON public.access_logs(ip_address);
CREATE INDEX IF NOT EXISTS idx_access_logs_accessed ON public.access_logs(accessed_at);

-- =========================================================================
-- updated_at auto-update trigger (replicates MySQL ON UPDATE CURRENT_TIMESTAMP)
-- =========================================================================
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['category_types','equipment_details','templates','packages']
    LOOP
        EXECUTE format(
            'DROP TRIGGER IF EXISTS trg_%s_updated ON public.%I', t, t
        );
        EXECUTE format(
            'CREATE TRIGGER trg_%s_updated BEFORE UPDATE ON public.%I
             FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', t, t
        );
    END LOOP;
END;
$$;